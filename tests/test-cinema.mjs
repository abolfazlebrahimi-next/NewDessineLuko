import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { JSDOM } from 'jsdom';

const dom = new JSDOM('<!doctype html><html><body><button id="origin">سینما</button><div id="overlay"><div id="labels"></div><div id="toasts"></div><div id="drag-ghost"></div></div></body></html>', { url: 'http://localhost/', pretendToBeVisual: true });
const { window } = dom;
Object.assign(globalThis, { window, document: window.document, localStorage: window.localStorage, HTMLElement: window.HTMLElement, requestAnimationFrame: (cb) => setTimeout(cb, 0) });
window.matchMedia = () => ({ matches: true });
const { UI } = await import('../src/ui.js');
const { MOVIES } = await import('../src/cinema.js');
const { state } = await import('../src/state.js');
const ui = new UI({ worldToScreen: () => ({ x: 0, y: 0 }) });
const origin = document.getElementById('origin');
const originalXp = state.xp;
origin.focus();
ui.openBuilding({ id: 'cinema' });
let panel = ui.activeModal;
assert(panel.classList.contains('panel-cinema'));
assert.equal(panel.getAttribute('role'), 'dialog');
assert.equal(panel.querySelector('h1').textContent, 'چه فیلمی دوست داری ببینی؟');
assert.equal(panel.querySelectorAll('[data-movie]').length, 5);
assert(panel.querySelector('.cinema-curtains'));
for (const movie of MOVIES) {
  assert(existsSync(`public/assets/cinema/${movie.id}.webp`));
  panel.querySelector(`[data-movie="${movie.id}"]`).click();
  assert.equal(panel.querySelector('.cinema-ticket h2').textContent, movie.title);
  assert(panel.querySelector('.cinema-program').hidden);
  const confirm = panel.querySelector('.cinema-confirm');
  confirm.click();
  assert(confirm.disabled);
  assert.equal(panel.dataset.selectedMovie, movie.id);
  assert(panel.querySelector('[role="status"]').textContent.includes(movie.title));
  document.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
  assert(panel.querySelector('.cinema-ticket').hidden);
  assert(!panel.querySelector('.cinema-program').hidden);
  assert.equal(document.activeElement.dataset.movie, movie.id);
}
assert.equal(state.xp, originalXp, 'Selection must not award watch XP without a video');
panel.querySelector('.cinema-close').focus();
document.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Tab', shiftKey: true, cancelable: true }));
assert.equal(document.activeElement.dataset.movie, 'castle', 'Keyboard focus wraps within dialog');
document.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape' }));
assert.equal(ui.activeModal, null);
assert.equal(document.activeElement, origin);
assert.equal(ui.modalCleanup, null);
ui.openBuilding({ id: 'cinema' });
ui.openMail();
assert(!ui.activeModal.classList.contains('panel-cinema'));
assert.equal(ui.modalCleanup, null, 'Replacing cinema must clean up listeners and timers');
ui.closeModal();
console.log('✓ Cinema: building integration, artwork, 5 selections, confirmation, Escape, keyboard focus, cleanup, and no unearned XP');
await new Promise((resolve) => setTimeout(resolve, 250));
window.close();
